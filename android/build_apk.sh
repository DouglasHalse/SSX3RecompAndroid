#!/usr/bin/env bash
# Build the SSX 3 Android APK from the native build in build-android/.
#
#   android/build_apk.sh            # debug-signed APK, ready to install
#
# Needs: the NDK build of libmain.so (build-android/), libSDL2.so from the
# SDL2 Android build, a JDK, and the Android build-tools + platform jars.
# Everything is packaged without Gradle: aapt2, javac, d8, zipalign, apksigner.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"

BT=${BT:-C:/Android/android-14}                     # build-tools 34
PLATFORM=${PLATFORM:-C:/Android/sdk/platforms/android-34/android.jar}
ABI=${ABI:-arm64-v8a}
SDL_LIB=${SDL_LIB:-C:/Android/sdl-prefix/lib/libSDL2.so}
OUT=${OUT:-build/android}
APK_NAME=${APK_NAME:-ssx3-debug.apk}
PKG=com.douglashalse.ssx3

# What this APK is built from, stamped into it so the launcher can say so and
# so two builds are never confused: a release build (RELEASE=1, cut by
# scripts/release.sh from a tag) carries the version alone; anything else
# carries the commit, because that is what identifies a tree that is not a
# release.
COMMIT=${COMMIT:-$(git rev-parse --short HEAD 2>/dev/null || echo unknown)}
# This APK is built from two repositories -- this one and the toolkit branch
# that supplies the runtime, the renderer and the touch pad -- so it names both.
TOOLKIT_DIR=${TOOLKIT_DIR:-$(cd "$ROOT/.." && pwd)/xboxrecomp}
TOOLKIT_COMMIT=${TOOLKIT_COMMIT:-$( (cd "$TOOLKIT_DIR" 2>/dev/null && git rev-parse --short HEAD 2>/dev/null) || true )}
BUILD_DATE=${BUILD_DATE:-$(date +%Y-%m-%d)}
VERSION_CODE=${VERSION_CODE:-$(git rev-list --count HEAD 2>/dev/null || echo 1)}
RELEASE=${RELEASE:-0}
if [ -n "${VERSION_NAME:-}" ]; then
    VERSION_NAME=${VERSION_NAME#v}
elif [ -n "${VERSION_BASE:-}" ]; then
    VERSION_NAME=${VERSION_BASE#v}
else
    # Our own tags only: the upstream history has its own v0.2.3 and that is
    # not this app's version.
    VERSION_NAME=$(git describe --tags --abbrev=0 --match 'android-v*' 2>/dev/null                    | sed 's/^android-v//' || true)
    VERSION_NAME=${VERSION_NAME:-0.0}
fi
[ "$RELEASE" = "1" ] || VERSION_NAME="$VERSION_NAME-dev-$COMMIT"

NATIVE=${NATIVE:-build-android/libmain.so}
IMPORT=${IMPORT:-build-android/libssx3import.so}
[ -f "$NATIVE" ] || { echo "missing $NATIVE: run the NDK build first" >&2; exit 1; }
[ -f "$IMPORT" ] || { echo "missing $IMPORT: run the NDK build first" >&2; exit 1; }
[ -f "$SDL_LIB" ] || { echo "missing $SDL_LIB" >&2; exit 1; }

rm -rf "$OUT"
mkdir -p "$OUT/res" "$OUT/gen" "$OUT/classes" "$OUT/dex" "$OUT/lib/$ABI"

echo "== build info ($VERSION_NAME, commit $COMMIT + toolkit $TOOLKIT_COMMIT, code $VERSION_CODE)"
mkdir -p "$OUT/gen/com/douglashalse/ssx3"
cat > "$OUT/gen/com/douglashalse/ssx3/BuildInfo.java" <<JAVA
package com.douglashalse.ssx3;

/** Generated by android/build_apk.sh: what this APK was built from. */
public final class BuildInfo {
    public static final String  VERSION = "$VERSION_NAME";
    public static final String  COMMIT  = "$COMMIT";
    public static final String  TOOLKIT = "$TOOLKIT_COMMIT";
    public static final String  DATE    = "$BUILD_DATE";
    public static final boolean RELEASE = $([ "$RELEASE" = "1" ] && echo true || echo false);

    private BuildInfo() {
    }
}
JAVA

echo "== manifest ($VERSION_NAME, code $VERSION_CODE)"
# aapt2's --version-code/--version-name do not override attributes the manifest
# already declares on this build-tools, so the manifest is stamped instead.
sed -e "s/android:versionCode=\"[0-9]*\"/android:versionCode=\"$VERSION_CODE\"/" \
    -e "s/android:versionName=\"[^\"]*\"/android:versionName=\"$VERSION_NAME\"/" \
    android/AndroidManifest.xml > "$OUT/AndroidManifest.xml"
grep -n 'android:version' "$OUT/AndroidManifest.xml" | head -2

echo "== resources"
"$BT/aapt2.exe" compile --dir android/res -o "$OUT/res/resources.zip"

echo "== manifest + resources -> base.apk"
"$BT/aapt2.exe" link -o "$OUT/base.apk" \
    -I "$PLATFORM" \
    --manifest "$OUT/AndroidManifest.xml" \
    --java "$OUT/gen" \
    --min-sdk-version 30 --target-sdk-version 34 \
    "$OUT/res/resources.zip"

echo "== java"
# javac 23's class files make D8 (build-tools 34) die with an internal NPE in
# its dex writer, so the Java side is compiled with a JDK 8 and dexed by the
# D8 shipped with build-tools 30. JDK8 / D8_JAR can point elsewhere.
JDK8=${JDK8:-C:/Program Files/Unity/Hub/Editor/2019.4.2f1/Editor/Data/PlaybackEngines/AndroidPlayer/OpenJDK}
D8_JAR=${D8_JAR:-C:/Program Files/Unity/Hub/Editor/2019.4.2f1/Editor/Data/PlaybackEngines/AndroidPlayer/SDK/build-tools/30.0.2/lib/d8.jar}
"$JDK8/bin/javac.exe" -nowarn -encoding UTF-8 -source 8 -target 8 \
    -classpath "$PLATFORM" -d "$OUT/classes" \
    $(find android/java "$OUT/gen" -name '*.java')

echo "== dex"
OUT_ABS=$(cd "$OUT" && pwd -W)   # C:/... : d8 rejects MSYS /c/... paths
"$JDK8/bin/java.exe" -cp "$D8_JAR" com.android.tools.r8.D8 --min-api 30 \
    --lib "$PLATFORM" --output "$OUT_ABS/dex" $(find "$OUT/classes" -name '*.class')

echo "== package"
cp "$NATIVE"  "$OUT/lib/$ABI/libmain.so"
cp "$IMPORT"  "$OUT/lib/$ABI/libssx3import.so"
cp "$SDL_LIB" "$OUT/lib/$ABI/libSDL2.so"
STRIP=${STRIP:-C:/Android/android-ndk-r27c/toolchains/llvm/prebuilt/windows-x86_64/bin/llvm-strip.exe}
[ -x "$STRIP" ] && "$STRIP" --strip-unneeded "$OUT/lib/$ABI/libmain.so" \
                          "$OUT/lib/$ABI/libssx3import.so" \
                          "$OUT/lib/$ABI/libSDL2.so"
python - "$OUT/base.apk" "$OUT/dex/classes.dex" \
    "$OUT/lib/$ABI/libmain.so" "$OUT/lib/$ABI/libssx3import.so" \
    "$OUT/lib/$ABI/libSDL2.so" "$ABI" <<'PY'
import sys, zipfile
apk, dex, libmain, libimport, libsdl, abi = sys.argv[1:7]
with zipfile.ZipFile(apk, "a", zipfile.ZIP_DEFLATED) as z:
    z.write(dex, "classes.dex")
    z.write(libmain, "lib/%s/libmain.so" % abi)
    z.write(libimport, "lib/%s/libssx3import.so" % abi)
    z.write(libsdl, "lib/%s/libSDL2.so" % abi)
PY

echo "== align + sign"
KS=android/ssx3-debug.keystore
if [ ! -f "$KS" ]; then
    "$JDK8/bin/keytool.exe" -genkeypair -keystore "$KS" -storepass android -keypass android \
        -alias ssx3 -keyalg RSA -keysize 2048 -validity 10000 \
        -dname "CN=SSX 3 Android port, O=local"
    echo "   created $KS"
fi
"$BT/zipalign.exe" -f 4 "$OUT/base.apk" "$OUT/aligned.apk"
"$BT/apksigner.bat" sign --ks "$KS" --ks-pass pass:android --key-pass pass:android \
    --v1-signing-enabled false --v2-signing-enabled true \
    --out "$OUT/$APK_NAME" "$OUT/aligned.apk"
"$BT/apksigner.bat" verify --print-certs "$OUT/$APK_NAME" | head -3

ls -la "$OUT/$APK_NAME"
echo
echo "install:  adb install -r $OUT/$APK_NAME"
echo "data:     adb push game <device>:/sdcard/Android/data/$PKG/files/ssx3/"
