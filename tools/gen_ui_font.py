"""Generate src/ui_font_data.h: the printable ASCII set rendered from a system
font at two sizes, as trimmed alpha bitmaps plus metrics -- a proportional
font for a port-drawn screen, with no rasteriser in the game.

    python tools/gen_ui_font.py

The port scales between the two sizes by height, so 480p and 4K both get
readable type from ~120 KB of data.
"""
from PIL import Image, ImageDraw, ImageFont
import os

FONT = r'C:\Windows\Fonts\segoeuib.ttf'
SIZES = (22, 34)
CHARS = [chr(c) for c in range(0x20, 0x7F)]
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   'src', 'ui_font_data.h')

blocks = []
tables = []
for size in SIZES:
    font = ImageFont.truetype(FONT, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    pixels = bytearray()
    for ch in CHARS:
        adv = int(round(font.getlength(ch)))
        bbox = font.getbbox(ch)
        w = max(0, bbox[2] - bbox[0])
        h = max(0, bbox[3] - bbox[1])
        off = len(pixels)
        if w and h:
            img = Image.new('L', (w, h), 0)
            ImageDraw.Draw(img).text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
            pixels += img.tobytes()
        glyphs.append((adv, bbox[0], bbox[1], w, h, off))
    # a printable first glyph ('.') keeps the array non-empty for empty windows
    assert len(pixels) > 0
    blocks.append((size, ascent, descent, glyphs, bytes(pixels)))

lines = []
lines.append('/* Generated by tools/gen_ui_font.py -- do not edit.')
lines.append(' *')
lines.append(' * Printable ASCII rendered from %s at %s px.' % (os.path.basename(FONT),
                                                               ', '.join(str(s) for s in SIZES)))
lines.append(' * Per glyph: advance, bearing x/y into the line box, trimmed width/height,')
lines.append(' * offset into the size\'s pixel run. Alpha only: the screen tints it.')
lines.append(' */')
lines.append('#ifndef UI_FONT_DATA_H')
lines.append('#define UI_FONT_DATA_H')
lines.append('')
lines.append('#define UI_FONT_FIRST 0x20')
lines.append('#define UI_FONT_COUNT %d' % len(CHARS))
lines.append('')
lines.append('typedef struct {')
lines.append('    short advance, bx, by, w, h;')
lines.append('    int off;')
lines.append('} ui_glyph;')
lines.append('')
lines.append('typedef struct {')
lines.append('    int px, ascent, descent;')
lines.append('    const ui_glyph *glyphs;')
lines.append('    const unsigned char *pixels;')
lines.append('} ui_face;')
lines.append('')

for i, (size, ascent, descent, glyphs, pixels) in enumerate(blocks):
    lines.append('static const ui_glyph s_glyphs_%d[UI_FONT_COUNT] = {' % size)
    for g in glyphs:
        lines.append('    {%d,%d,%d,%d,%d,%d},' % g)
    lines.append('};')
    lines.append('')
    lines.append('static const unsigned char s_pixels_%d[%d] = {' % (size, len(pixels)))
    row = []
    for k, byte in enumerate(pixels):
        row.append('%d' % byte)
        if len(row) == 24:
            lines.append('    ' + ','.join(row) + ',')
            row = []
    if row:
        lines.append('    ' + ','.join(row) + ',')
    lines.append('};')
    lines.append('')

lines.append('static const ui_face s_faces[%d] = {' % len(blocks))
for size, ascent, descent, glyphs, pixels in blocks:
    lines.append('    {%d, %d, %d, s_glyphs_%d, s_pixels_%d},' % (size, ascent, descent, size, size))
lines.append('};')
lines.append('')
lines.append('#endif')
lines.append('')

open(OUT, 'w', newline='\n').write('\n'.join(lines))
total = sum(len(b[4]) for b in blocks)
print('wrote %s: %d sizes, %d glyphs, %.1f KB of pixels' % (OUT, len(blocks), len(CHARS), total / 1024.0))
